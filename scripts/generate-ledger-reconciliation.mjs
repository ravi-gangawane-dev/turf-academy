import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

// Generates deployment/backend-release-2026-10-19/03-ledger-reconciliation.sql from the
// six already-applied column-control migrations so the ledger entries embed the exact
// source that is actually running in the database.
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const versions = [
  ['202610140003', 'staff_column_controls'],
  ['202610140004', 'student_parent_columns'],
  ['202610140005', 'payment_columns'],
  ['202610140006', 'attendance_table_columns'],
  ['202610140007', 'enrollment_history_columns'],
  ['202610140008', 'student_detail_columns'],
];
const preconditionFn = {
  '202610140003': 'get_staff_list_page',
  '202610140004': 'get_student_columns_page',
  '202610140005': 'get_payment_list_page',
  '202610140006': 'get_attendance_table_page',
  '202610140007': 'list_columns_match',
  '202610140008': 'get_student_detail_page',
};
const TAG = 'ledger_source';
const out = [
  '-- Ledger reconciliation for the six already-applied column-control migrations (202610140003-0008).',
  '-- Generated by scripts/generate-ledger-reconciliation.mjs from supabase/migrations/.',
  '-- Records migration-history entries ONLY; it applies no schema changes.',
  '-- Run inside one transaction. The script ends with ROLLBACK: review the printed rows,',
  '-- then re-run changing the final rollback to commit if the output is correct.',
  'begin;',
  '',
  '-- Precondition: the functions these migrations created must already exist, proving the',
  '-- migrations were applied and only their ledger entries are missing.',
  'do $$ begin',
];
for (const [v] of versions) {
  out.push(
    `  if not exists (select 1 from pg_proc where proname='${preconditionFn[v]}') then ` +
      `raise exception 'PRECONDITION FAILED: ${preconditionFn[v]} missing - do not record ${v}'; end if;`,
  );
}
out.push('end $$;', '');
for (const [v, name] of versions) {
  const body = readFileSync(join(root, 'supabase/migrations', `${v}_${name}.sql`), 'utf8')
    .replace(/\r\n/g, '\n')
    .trim();
  if (body.includes(TAG)) throw new Error(`dollar-tag collision in ${v}`);
  out.push(
    `insert into supabase_migrations.schema_migrations(version,name,statements) ` +
      `values ('${v}','${name}',array[$${TAG}$\n${body}\n$${TAG}$]) on conflict (version) do nothing;`,
    '',
  );
}
out.push(
  `select version,name from supabase_migrations.schema_migrations where version like '2026101400%' order by version;`,
  'rollback;',
  '-- Change the final ROLLBACK to COMMIT only after reviewing the printed rows.',
  '',
);
const target = join(root, 'deployment/backend-release-2026-10-19/03-ledger-reconciliation.sql');
writeFileSync(target, out.join('\n'));
console.log('written', target);
